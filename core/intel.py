"""
Eigene Threat-Intel aus dem Verlauf.

* YARA-Regel je Cluster (IOC-Graph): aus den IOCs, die die Dateien des Clusters
  TEILEN, plus gemeinsamem Imphash. Die Regel entsteht allein aus den
  gespeicherten Befunden – die Originaldateien werden nicht erneut geöffnet.
* Rückwärtstest gegen den gesamten Verlauf: wie viele Dateien im / außerhalb des
  Clusters würde die Regel treffen? (Simulation über die gespeicherten IOCs.)
* Aktivieren = Regel nach data/yara_generated/ schreiben → der YARA-Analysator
  (und damit auch der Watch-Folder) nutzt sie ab der nächsten Datei.
* Export: STIX 2.1 Bundle, MISP-Event (JSON), CSV.
"""
import csv
import datetime
import json
import re
import uuid
from pathlib import Path

from config.settings import APP_CODENAME, APP_VERSION, DATA_DIR

GENERATED_DIR = DATA_DIR / "yara_generated"
RULE_TYPES = ("domain", "ipv4", "email", "onion", "btc", "xmr", "unc_path")
_NS = uuid.UUID("6f2b1c1e-5e3a-4d1b-9a55-5e7e1e0f4a11")          # für stabile STIX-IDs


def _yara_str(v):
    return v.replace("\\", "\\\\").replace('"', '\\"')


def _rule_name(text):
    n = re.sub(r"[^A-Za-z0-9_]", "_", text).strip("_")
    return ("SENTINEL_GEN_" + n)[:120]


def _cluster_facts(db, graph, cluster):
    files = [graph["files"][s] for s in cluster["files"]]
    iocs = [i for i in graph["iocs"] if i["key"] in set(cluster["iocs"]) and i["type"] in RULE_TYPES]
    imps = {}
    for f in files:
        fp = db.fingerprints_for(f["id"])
        if fp.get("imphash"):
            imps.setdefault(fp["imphash"], []).append(f["name"])
    shared_imp = [h for h, names in imps.items() if len(names) >= 2]
    return files, iocs, shared_imp


def cluster_rule(db, graph, cluster, name=None):
    """→ {'name', 'text', 'iocs', 'imphashes', 'threshold'} oder None, wenn nichts Belastbares da ist."""
    files, iocs, imps = _cluster_facts(db, graph, cluster)
    if not iocs and not imps:
        return None
    rname = _rule_name(name or f"{cluster.get('name', 'cluster')}_{datetime.date.today():%Y%m%d}")
    threshold = _tune_threshold(db, iocs, imps, {f["sha256"] for f in files})
    lines = ['import "pe"', "", f"rule {rname}", "{", "    meta:",
             f'        description = "Generated by {APP_CODENAME} from {len(files)} related files '
             f'({len(iocs)} shared IOCs)"',
             f'        author = "{APP_CODENAME} {APP_VERSION}"',
             f'        date = "{datetime.date.today().isoformat()}"',
             '        severity = "high"',
             f'        files = "{_yara_str(", ".join(f["name"] for f in files)[:400])}"']
    if iocs:
        lines.append("    strings:")
        for n, i in enumerate(iocs[:40]):
            lines.append(f'        $ioc{n} = "{_yara_str(i["value"])}" ascii wide nocase   // {i["type"]}')
    conds = []
    if iocs:
        conds.append(f"{min(threshold, len(iocs))} of ($ioc*)")
    for h in imps:
        conds.append(f'pe.imphash() == "{h}"')
    lines += ["    condition:", "        " + " or ".join(conds), "}", ""]
    return {"name": rname, "text": "\n".join(lines), "iocs": [i["value"] for i in iocs[:40]],
            "imphashes": imps, "threshold": min(threshold, len(iocs)) if iocs else 0,
            "cluster_files": [f["sha256"] for f in files]}


def _tune_threshold(db, iocs, imps, cluster):
    """Schwelle „N of ($ioc*)“ per Rückwärtstest: volle Cluster-Abdeckung ohne Fremdtreffer, möglichst streng."""
    if len(iocs) <= 1:
        return 1
    best, best_val = 1, None
    for t in range(min(len(iocs), 4), 0, -1):
        bt = backtest(db, {"iocs": [i["value"] for i in iocs], "imphashes": imps, "threshold": t,
                           "cluster_files": list(cluster)})
        val = len(bt["inside"]) - 3 * len(bt["outside"])
        if len(bt["inside"]) == len(cluster) and not bt["outside"]:
            return t
        if best_val is None or val > best_val:
            best, best_val = t, val
    return best


def compile_check(text):
    """→ None wenn OK, sonst Fehlermeldung (yara nicht installiert → None, Hinweis im UI)."""
    try:
        import yara
    except ImportError:
        return None
    try:
        yara.compile(source=text)
        return None
    except yara.Error as e:
        return str(e)


def backtest(db, rule):
    """Simuliert die Regel über alle gespeicherten Analysen (IOCs + Imphash)."""
    want = {v.lower() for v in rule["iocs"]}
    imps = set(rule["imphashes"])
    inside, outside = [], []
    cluster = set(rule["cluster_files"])
    seen = set()
    for row in db.list_analyses(limit=100000):
        if row["sha256"] in seen:
            continue
        seen.add(row["sha256"])
        vals = {r["value"].lower() for r in db.iocs_for(row["id"])}
        hits = sum(1 for w in want if any(w in v for v in vals))
        fp = db.fingerprints_for(row["id"])
        match = (rule["threshold"] and hits >= rule["threshold"]) or (fp.get("imphash") in imps)
        if match:
            (inside if row["sha256"] in cluster else outside).append(row)
    return {"inside": inside, "outside": outside, "cluster_size": len(cluster)}


def activate(rule, directory=None):
    d = Path(directory or GENERATED_DIR)
    d.mkdir(parents=True, exist_ok=True)
    path = d / f"{rule['name']}.yar"
    path.write_text(rule["text"], encoding="utf-8")
    return path


def generated_rules(directory=None):
    d = Path(directory or GENERATED_DIR)
    return sorted(d.glob("*.yar")) if d.is_dir() else []


